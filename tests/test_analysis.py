from __future__ import annotations

from online_school import (
    AnalysisService,
    DefaultAnalysisContext,
    LengthAnalyzer,
    TemplateAnalyzer,
    default_analyzer_registry,
)
from tests.conftest import valid_payload
from online_school.validation import validate_submission


def test_length_analyzer_returns_explanation_without_score(catalog) -> None:
    submission = validate_submission(
        valid_payload(text="one\n\n two", code="x = 1\n\n"),
        catalog,
    )
    report = LengthAnalyzer().analyze(
        submission,
        DefaultAnalysisContext(catalog.get("py-intro-1")),
    )
    assert report.analyzer_id == "length"
    assert report.rubric_feedback.score is None
    assert "text=2" in report.rubric_feedback.message
    assert "code=1" in report.rubric_feedback.message


def test_template_analyzer_reports_allowed_exact_lines(catalog) -> None:
    template = "# generated by course"
    assignment = type(catalog.get("py-intro-1"))(
        "py-intro-1",
        "Функции и тесты",
        (template,),
    )
    submission = validate_submission(
        valid_payload(text=template, code="return 1"),
        type(catalog)((assignment,)),
    )
    report = TemplateAnalyzer().analyze(
        submission,
        DefaultAnalysisContext(assignment),
    )
    assert report.similarity == 0.5
    assert report.evidence[0].start_line == 1
    assert "разрешённым" in report.rubric_feedback.message


def test_registry_service_selects_analyzer_without_type_branching(catalog) -> None:
    submission = validate_submission(valid_payload(), catalog)
    service = AnalysisService(default_analyzer_registry())
    report = service.analyze(
        submission,
        "length",
        DefaultAnalysisContext(catalog.get("py-intro-1")),
    )
    assert report.analyzer_id == "length"

